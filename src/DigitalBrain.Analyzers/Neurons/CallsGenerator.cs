using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace DigitalBrain.Analyzers.Neurons;

/// <summary>
/// Records, as <c>[assembly: DigitalBrain.Calls(from, to)]</c>, every contract a <c>[Neuron]</c> or <c>[App]</c> class calls through
/// <c>Get&lt;T&gt;(…)</c>. The brain graph reads the attributes to draw <c>calls</c> edges and find call cycles.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class CallsGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var calls = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is InvocationExpressionSyntax { Expression: GenericNameSyntax or MemberAccessExpressionSyntax { Name: GenericNameSyntax } },
                static (ctx, ct) => Call(ctx, ct))
            .Where(static call => call is not null)
            .Select(static (call, _) => call!.Value)
            .Collect();
        context.RegisterSourceOutput(calls, static (spc, pairs) => Emit(spc, pairs));
    }

    private static (string From, string To)? Call(GeneratorSyntaxContext context, System.Threading.CancellationToken cancellationToken)
    {
        var invocation = (InvocationExpressionSyntax)context.Node;
        var name = invocation.Expression switch
        {
            GenericNameSyntax generic => generic,
            MemberAccessExpressionSyntax { Name: GenericNameSyntax generic } => generic,
            _ => null,
        };
        if (name is null || name.Identifier.ValueText != "Get" || name.TypeArgumentList.Arguments.Count != 1) { return null; }
        var info = context.SemanticModel.GetSymbolInfo(invocation, cancellationToken);
        if ((info.Symbol ?? info.CandidateSymbols.FirstOrDefault()) is not IMethodSymbol { TypeArguments.Length: 1 } method) { return null; }
        if (!IsNeuronOrAppGet(method)) { return null; }
        var owner = invocation.Ancestors().OfType<TypeDeclarationSyntax>().FirstOrDefault();
        if (owner is null || context.SemanticModel.GetDeclaredSymbol(owner, cancellationToken) is not INamedTypeSymbol type) { return null; }
        var from = NameOf(type);
        if (from is null) { return null; }
        var contract = method.TypeArguments[0];
        var alias = contract.GetAttributes().FirstOrDefault(a => a.AttributeClass?.Name == "NeuronAliasAttribute")?.ConstructorArguments.FirstOrDefault().Value as string;
        return (from, alias ?? contract.Name);
    }

    // The Get of Neuron, App or their contexts: the method lives on a type named Neuron, App, INeuronContext or a base of one of them.
    private static bool IsNeuronOrAppGet(IMethodSymbol method)
    {
        for (var type = method.ContainingType; type is not null; type = type.BaseType)
        {
            if (type.Name is "Neuron" or "App" or "INeuronContext" && type.ContainingNamespace?.ToDisplayString().StartsWith("DigitalBrain", StringComparison.Ordinal) == true) { return true; }
        }
        return false;
    }

    private static string? NameOf(INamedTypeSymbol type)
    {
        for (var current = type; current is not null; current = current.ContainingType)
        {
            foreach (var attribute in current.GetAttributes())
            {
                if (attribute.AttributeClass?.Name is "NeuronAttribute" or "AppAttribute" && attribute.ConstructorArguments.Length > 0 && attribute.ConstructorArguments[0].Value is string name)
                { return name; }
            }
        }
        return null;
    }

    private static void Emit(SourceProductionContext context, ImmutableArray<(string From, string To)> pairs)
    {
        if (pairs.IsDefaultOrEmpty) { return; }
        var builder = new StringBuilder("// <auto-generated/> DigitalBrain calls edges for the brain graph.\n");
        foreach (var (from, to) in pairs.Distinct().OrderBy(p => p.From, StringComparer.Ordinal).ThenBy(p => p.To, StringComparer.Ordinal))
        {
            builder.Append("[assembly: global::DigitalBrain.Calls(").Append(Literal(from)).Append(", ").Append(Literal(to)).Append(")]\n");
        }
        context.AddSource("DigitalBrain.Calls.g.cs", builder.ToString());
    }

    private static string Literal(string value) => SyntaxFactory.Literal(value).ToFullString();
}
