    public static bool IsAdditionalCurrency(string currencyCode)
    {
        return !string.IsNullOrWhiteSpace(currencyCode) &&
               _additionalCurrencies.Contains(currencyCode.Trim().ToUpperInvariant());
    }

    public static string NormalizeCurrencyCode(string currencyCode)
    {
        return string.IsNullOrWhiteSpace(currencyCode) ? string.Empty : currencyCode.Trim().ToUpperInvariant();
    }
